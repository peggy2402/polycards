  subtotal?: number;
  vatRate?: number; // 0, 5, 8, 10
  vatAmount?: number;
  creditAmount: number; // Phát sinh Có: Số tiền khách hàng cần thanh toán
  debitAmount: number; // Phát sinh Nợ: Số tiền khách hàng đã thanh toán
